#!/bin/sh
# Свой X-сервер для приватного образа с платформой 1С — без посредника в цепочке сигналов.
#
# ЗАЧЕМ ЭТО ВМЕСТО `xvfb-run`. Толстый клиент 1С слинкован с GTK3/X11 и без
# DISPLAY не стартует вовсе («Unable to initialize GTK+ or connect to the
# windowing system», код 255 — проверено на 8.3.27.2130). X-сервер нужен.
# Но `xvfb-run` запускает команду ДОЧЕРНИМ процессом и ждёт её, чтобы потом
# погасить X. Из-за этого SIGTERM от `docker stop` достаётся посреднику, а не
# синхронизации: посредник завершается первым, работа обрывается без всякой
# уборки, и `stop_grace_period` в docker/compose.yaml не работает вовсе.
# Проверено запуском: контейнер останавливался мгновенно с кодом 143, а
# обработчик в команде не срабатывал ни разу.
#
# Здесь X-сервер поднимается рядом, а команда запускается через `exec`: она
# ЗАНИМАЕТ МЕСТО этого скрипта и получает сигналы сама. Xvfb остаётся её
# потомком и исчезает вместе с контейнером.
#
# Номер дисплея выбирает сам Xvfb и сообщает его через `-displayfd`. Это
# надёжнее ключа `-a` у `xvfb-run`: тот подбирает номер перебором и в двух
# одновременно стартующих контейнерах способен выбрать один и тот же.
set -eu

SCREEN="${GITSYNC_XVFB_SCREEN:-1024x768x24}"

if [ "$#" -eq 0 ]; then
    printf '%s\n' "xvfb-entrypoint: не передана команда для запуска" >&2
    exit 2
fi

display_file="$(mktemp)"
xvfb_log="$(mktemp)"
# Файлы нужны только на время старта; команда получает уже готовый DISPLAY.
trap 'rm -f "$display_file" "$xvfb_log"' EXIT INT TERM

# Вывод Xvfb уводится в файл, а НЕ наследует stdout/stderr команды. Две причины:
# stdout принадлежит выводу самой команды и засорять его нельзя; и живой
# X-сервер, держащий эти дескрипторы открытыми, не дал бы вызывающей стороне
# дождаться конца вывода после завершения команды.
Xvfb -displayfd 3 -screen 0 "$SCREEN" -nolisten tcp 3>"$display_file" >"$xvfb_log" 2>&1 &
xvfb_pid=$!

# Ждём, пока Xvfb сообщит занятый им номер дисплея. Ожидание ограничено:
# неподнявшийся X-сервер обязан приводить к понятному отказу здесь, а не к
# падению конфигуратора где-то в середине работы.
waited=0
while [ ! -s "$display_file" ]; do
    if ! kill -0 "$xvfb_pid" 2>/dev/null; then
        break
    fi
    if [ "$waited" -ge 100 ]; then
        break
    fi
    waited=$((waited + 1))
    sleep 0.1
done

if [ ! -s "$display_file" ]; then
    kill "$xvfb_pid" 2>/dev/null || true
    printf '%s\n' "xvfb-entrypoint: Xvfb не запустился и не сообщил номер дисплея." >&2
    printf '%s\n' "Толстый клиент 1С без X-сервера не работает, поэтому запуск остановлен." >&2
    printf '%s\n' "Проверьте, что в образе есть пакет xvfb (docker/Dockerfile.native)." >&2
    printf '%s\n' "--- вывод Xvfb ---" >&2
    cat "$xvfb_log" >&2 || true
    exit 2
fi

DISPLAY=":$(cat "$display_file")"
export DISPLAY
rm -f "$display_file" "$xvfb_log"
trap - EXIT INT TERM

# exec — принципиально: дальше в цепочке процессов посредников нет, и SIGTERM
# от `docker stop` приходит самой синхронизации.
exec "$@"
