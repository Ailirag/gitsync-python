#!/bin/sh
# Предполётная проверка контейнера gitsync-py.
#
# Правило одно: если условие корректной работы не выполнено — останавливаемся ЗДЕСЬ
# и печатаем, что именно сделать. Молчаливое продолжение в этих случаях означает
# либо испорченную историю Git, либо два конфигуратора в хранилище под одним логином.
#
# Ничего не чинится «само»: контейнер не меняет владельца чужих каталогов и не
# выдаёт Git разрешение доверять любому каталогу.
set -eu

fail() {
    # Сообщения — на stderr: stdout принадлежит выводу самой команды.
    printf '%s\n' "gitsync: предполётная проверка не пройдена." >&2
    printf '%s\n' "$@" >&2
    exit 78  # EX_CONFIG: ошибка настройки, а не сбой синхронизации
}

note() { printf '%s\n' "gitsync: $*" >&2; }

# --- 1. Инструменты ---------------------------------------------------------
command -v git >/dev/null 2>&1 || fail \
    "В образе нет git. Собран не тот образ: ядру нужен git (docker/Dockerfile.core)."
command -v gitsync-py >/dev/null 2>&1 || fail \
    "В образе нет команды gitsync-py. Колесо пакета не установлено — пересоберите образ."

# --- 2. Учётная запись -------------------------------------------------------
# Образ рассчитан на обычного пользователя. Под root всё, что окажется в подключённых
# каталогах, достанется root, и следующий запуск под обычным UID не сможет это
# переписать. Поэтому здесь отказ, а не предупреждение: разбирать чужих владельцев
# в рабочей копии Git потом дороже, чем не создать их сейчас.
if [ "$(id -u)" = "0" ]; then
    if [ "${GITSYNC_ALLOW_ROOT:-}" = "1" ]; then
        note "ВНИМАНИЕ: контейнер запущен от root (GITSYNC_ALLOW_ROOT=1);"
        note "файлы в подключённых каталогах получат владельца root."
    else
        fail "Контейнер запущен от root." \
             "Образ рассчитан на обычного пользователя: файлы в подключённых каталогах" \
             "получили бы владельца root, и обычный запуск перестал бы работать." \
             "Запускайте своим пользователем и группой 0 (каталоги образа принадлежат app:0):" \
             "  docker run --user \"\$(id -u):0\" ..." \
             "Разовая подготовка тома действительно от root — задайте GITSYNC_ALLOW_ROOT=1."
    fi
fi

# UID, которого нет в /etc/passwd образа, работоспособен для самой синхронизации,
# но OpenSSH спрашивает getpwuid ещё до сети и отказывается работать вовсе
# («No user exists for uid …»). Отправка в Git по ssh — отдельная служба, её этот
# скрипт не видит, поэтому предупреждаем здесь, а не молчим до отказа там.
if ! id -un >/dev/null 2>&1; then
    note "ВНИМАНИЕ: UID $(id -u) не описан в /etc/passwd образа."
    note "Синхронизация от этого не страдает, а вот ssh откажет: «No user exists for uid $(id -u)»."
    note "Для отправки по ssh соберите образ под свой UID/GID"
    note "(--build-arg APP_UID=\$(id -u) --build-arg APP_GID=\$(id -g))"
    note "либо запускайте отправку пользователем образа."
fi

# --- 3. Домашний каталог -----------------------------------------------------
# Python определяет HOME в том числе по /etc/passwd. При запуске с произвольным UID
# (`--user 12345:0`) записи в passwd нет, и без HOME домашний каталог не определяется.
if [ -z "${HOME:-}" ]; then
    fail "Переменная HOME не задана." \
         "Запустите контейнер с -e HOME=/home/app и подключите туда каталог с правом записи."
fi
if ! mkdir -p "$HOME" 2>/dev/null || [ ! -w "$HOME" ]; then
    fail "Домашний каталог <$HOME> недоступен для записи пользователю $(id -u):$(id -g)." \
         "Каталоги образа принадлежат app:0 и открыты на запись группе 0, поэтому штатный" \
         "запуск — свой UID и группа 0:" \
         "  docker run --user \"\$(id -u):0\" ..." \
         "Нужен именно свой GID — соберите образ под него:" \
         "  docker build -f docker/Dockerfile.core --target core \\" \
         "    --build-arg APP_UID=\$(id -u) --build-arg APP_GID=\$(id -g) -t gitsync-py:core ." \
         "Если /home/app подключён томом, созданным другим UID, — смените владельца тома" \
         "или подключите том, созданный этим запуском."
fi

# --- 4. Общий каталог блокировок входа в хранилище ---------------------------
# Это НЕ кэш и не временные файлы: пока файл заблокирован, второй конфигуратор
# не войдёт в то же хранилище под тем же логином. Каталог обязан быть ОДНИМ
# томом для всех сотрудничающих контейнеров хоста и под ОДНИМ UID: файл
# блокировки создаётся с правами 0600 и другому пользователю не откроется.
SESSION_DIR="${GITSYNC_SESSION_DIR:-}"
if [ -n "$SESSION_DIR" ]; then
    case "$SESSION_DIR" in
        /*) : ;;
        *) fail "GITSYNC_SESSION_DIR=<$SESSION_DIR> должен быть абсолютным путём." ;;
    esac
    if ! mkdir -p "$SESSION_DIR" 2>/dev/null || [ ! -w "$SESSION_DIR" ]; then
        fail "Каталог блокировок <$SESSION_DIR> недоступен для записи пользователю $(id -u):$(id -g)." \
             "Подключите сюда общий именованный том и запускайте все контейнеры одним UID:" \
             "  docker volume create gitsync-sessions" \
             "  docker run ... --user \"\$(id -u):0\" -v gitsync-sessions:$SESSION_DIR ..." \
             "Новый том получает владельца и права от каталога образа (app:0, запись группе 0)," \
             "поэтому с группой 0 он готов к работе без смены владельца." \
             "Если том уже создан другим UID — смените владельца тома или запуск."
    fi
fi

# --- 5. Временные каталоги ---------------------------------------------------
# Выгрузка конфигуратора не должна попадать внутрь рабочей копии Git: инструмент
# это запрещает, поэтому нужен отдельный каталог с правом записи.
WORK_TMP="${GITSYNC_WORK_TMP:-/work/tmp}"
if [ -d "$WORK_TMP" ] && [ ! -w "$WORK_TMP" ]; then
    fail "Каталог временных файлов <$WORK_TMP> недоступен для записи пользователю $(id -u):$(id -g)." \
         "Подключите к нему том с правом записи для этого UID."
fi

# --- 6. Часовой пояс ---------------------------------------------------------
# Дата версии в отчёте хранилища приходит БЕЗ смещения и трактуется как местное
# время. Без заданного TZ контейнер считает местным UTC, и та же самая версия
# получит в Git другое время (и другой SHA), чем при запуске на Windows-машине.
case " $* " in
    *" sync "*|*" sync-all "*|*" clone "*)
        if [ -z "${TZ:-}" ] && [ "${GITSYNC_ALLOW_DEFAULT_TZ:-}" != "1" ]; then
            fail "Не задан часовой пояс (TZ)." \
                 "Время версии приходит из хранилища без смещения и считается местным." \
                 "Без TZ контейнер примет за местное UTC, и коммиты получат другое время," \
                 "чем при запуске на машине с 1С." \
                 "Укажите пояс ИСТОЧНИКА, например: -e TZ=Europe/Moscow" \
                 "Осознанно согласны на UTC — задайте GITSYNC_ALLOW_DEFAULT_TZ=1."
        fi
        ;;
esac

# --- 7. Владелец рабочей копии Git -------------------------------------------
# Подключённый каталог почти всегда принадлежит другому UID, и Git отказывается
# с ним работать. Отказ здесь нагляднее, чем на середине синхронизации.
REPO="${GITSYNC_REPO:-/repo}"
if [ -d "$REPO/.git" ] && ! probe="$(LC_ALL=C git -C "$REPO" rev-parse --is-inside-work-tree 2>&1)"; then
    case "$probe" in
        *"dubious ownership"*)
            if [ "${GITSYNC_TRUST_REPO:-}" = "1" ]; then
                # Разрешается РОВНО этот путь. Разрешение «*» не выдаётся никогда.
                git config --global --add safe.directory "$REPO"
                note "владелец каталога <$REPO> отличается от UID запуска;"
                note "разрешён явно только этот путь (GITSYNC_TRUST_REPO=1)."
            else
                fail "Git отказался работать с рабочей копией <$REPO>: у каталога другой владелец." \
                     "Каталог принадлежит UID $(stat -c %u "$REPO" 2>/dev/null || echo '?'), контейнер запущен от $(id -u)." \
                     "Выберите одно:" \
                     "  1) сменить владельца каталога на хосте: chown -R $(id -u):$(id -g) <каталог на хосте>" \
                     "  2) запустить контейнер владельцем каталога: --user <UID>:<GID>" \
                     "  3) если владелец доверенный — разрешить ИМЕННО этот путь: -e GITSYNC_TRUST_REPO=1" \
                     "Разрешение вида safe.directory со звёздочкой означает «доверять любому" \
                     "каталогу» и здесь не используется."
            fi
            ;;
        *)
            fail "Git не смог открыть рабочую копию <$REPO>:" "$probe"
            ;;
    esac
fi

exec gitsync-py "$@"
