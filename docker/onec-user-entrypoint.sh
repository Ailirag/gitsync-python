#!/bin/sh
# Разрешимая учётная запись текущего UID — без неё толстый клиент 1С падает.
#
# ЧТО ИМЕННО ПРОВЕРЕНО (8.3.27.2130, приватный образ, Docker 29.1.3):
#   --user 10001:0  (UID описан в /etc/passwd) → `1cv8 CREATEINFOBASE` код 0, база создана;
#   --user 12345:0  (UID не описан)            → Segmentation fault (core dumped), код 139,
#                                                базы нет, файл /Out не создан;
#                                                USER/LOGNAME в окружении не помогают;
#   --user 12345:0  + /etc/passwd с записью о 12345 → снова код 0 и настоящая база.
# То есть платформе нужен успешный `getpwuid` для собственного UID, а образ рассчитан
# на запуск с произвольным UID (см. docker/Dockerfile.core). Эта обёртка закрывает разрыв:
# дописывает запись о текущем UID и уступает своё место команде.
#
# Приём стандартный для образов, работающих с произвольным UID: право дозаписи даётся
# ГРУППЕ 0, под которой такие контейнеры и запускают (`--user <любой>:0`). Дописать строку
# в /etc/passwd — не повышение прав: UID процесса уже задан снаружи и не меняется.
#
# Отказ дописать запись НЕ останавливает запуск: команда может вовсе не обращаться к
# платформе (`--help`, работа с git), а причину будущего падения оператор увидит в
# предупреждении здесь, а не в безымянном коде 139 посреди синхронизации.
set -eu

# Путь вынесен в переменную, чтобы обёртку можно было проверить на копии файла.
PASSWD_FILE="${GITSYNC_PASSWD_FILE:-/etc/passwd}"

if [ "$#" -eq 0 ]; then
    printf '%s\n' "onec-user-entrypoint: не передана команда для запуска" >&2
    exit 2
fi

uid="$(id -u)"
gid="$(id -g)"

uid_is_known() {
    [ -r "$PASSWD_FILE" ] || return 1
    cut -d: -f3 "$PASSWD_FILE" 2>/dev/null | grep -qx "$uid"
}

if ! uid_is_known; then
    # Имя с номером UID: фиксированное имя столкнулось бы с уже существующей учётной записью.
    entry="gitsync-${uid}:x:${uid}:${gid}:gitsync arbitrary uid:${HOME:-/home/app}:/usr/sbin/nologin"
    if [ -w "$PASSWD_FILE" ] && printf '%s\n' "$entry" >> "$PASSWD_FILE" 2>/dev/null; then
        printf '%s\n' "onec-user-entrypoint: добавлена учётная запись для UID ${uid}" >&2
    else
        printf '%s\n' \
            "onec-user-entrypoint: UID ${uid} не описан в ${PASSWD_FILE}, а дописать туда нельзя." >&2
        printf '%s\n' \
            "Толстый клиент 1С в таком окружении завершается по SIGSEGV (код 139) без сообщения." >&2
        printf '%s\n' \
            "Запустите контейнер с --user 10001:0 либо подключите свой /etc/passwd с этим UID." >&2
    fi
fi

# exec — принципиально: посредника между командой и docker stop не остаётся.
exec "$@"
